class ManimRenderWorker(QThread):
    """Background worker thread to render Manim video animations without freezing UI.

    Supports both high-performance in-process rendering (zero external CLI requirements)
    and automatic fallback to subprocess execution via virtual environments or system Python.
    """

    progress_log = pyqtSignal(str)
    render_finished = pyqtSignal(bool, str, str)  # success, message, video_path

    def __init__(self, script_path: str, output_dir: str, code_content: str):
        super().__init__()
        self.script_path = script_path
        self.output_dir = output_dir
        self.code_content = code_content
        self.video_path = ""

    def run(self):
        # 1. Primary Strategy: In-Process Rendering via Python Manim library
        try:
            import manim
            from manim import config, Scene

            self.progress_log.emit("Executing Manim rendering engine (in-process)...\n")

            # Configure Manim for offline preview
            config.media_dir = self.output_dir
            config.quality = "low_quality"
            config.preview = False

            # Capture logs from Manim logger to emit to UI QTextEdit
            class LogSignalHandler(logging.Handler):
                def __init__(self, emitter):
                    super().__init__()
                    self.emitter = emitter

                def emit(self, record):
                    try:
                        self.emitter.emit(self.format(record))
                    except Exception:
                        pass

            log_handler = LogSignalHandler(self.progress_log)
            manim.logger.addHandler(log_handler)

            try:
                # Compile and execute the user script in an isolated namespace
                scope = {"__name__": "__main__", "__file__": self.script_path}
                code_obj = compile(self.code_content, self.script_path, "exec")
                exec(code_obj, scope)

                # Locate the Scene class
                scene_cls = scope.get("GraphAnimationScene")
                if scene_cls is None:
                    for obj in scope.values():
                        if isinstance(obj, type) and issubclass(obj, Scene) and obj is not Scene:
                            scene_cls = obj
                            break

                if scene_cls is None:
                    raise ValueError("No Scene subclass (e.g. GraphAnimationScene) found in script.")

                self.progress_log.emit(f"Rendering scene: {scene_cls.__name__}...\n")
                scene = scene_cls()
                scene.render()

                movie_file = getattr(scene.renderer.file_writer, "movie_file_path", None)
                if movie_file and os.path.exists(movie_file):
                    self.video_path = str(movie_file)
                else:
                    # Scan output_dir for any generated mp4
                    mp4s = list(Path(self.output_dir).rglob("*.mp4"))
                    full_mp4s = [p for p in mp4s if "partial_movie_files" not in str(p)]
                    target = full_mp4s[-1] if full_mp4s else (mp4s[-1] if mp4s else None)
                    if target and target.exists():
                        self.video_path = str(target)

                if self.video_path:
                    self.progress_log.emit(f"\nRender Complete! Output saved to:\n{self.video_path}\n")
                    self.render_finished.emit(True, "Animation rendered successfully!", self.video_path)
                    return
                else:
                    raise FileNotFoundError("Video file was not generated by scene.render().")

            finally:
                manim.logger.removeHandler(log_handler)

        except ImportError:
            self.progress_log.emit("In-process Manim not importable; searching for external Python/CLI environment...\n")
        except Exception as e:
            self.progress_log.emit(f"In-process render encountered notice: {e}\nFalling back to external runner...\n")

        # 2. Secondary Strategy: External CLI / Python Subprocess Fallback
        candidates = [
            Path(__file__).resolve().parent.parent.parent / ".venv" / "bin" / "manim",
            Path(__file__).resolve().parent.parent.parent / ".venv" / "bin" / "python",
            Path.home() / "CalculatorApp" / ".venv" / "bin" / "manim",
            Path.home() / "CalculatorApp" / ".venv" / "bin" / "python",
            Path.home() / ".venv" / "bin" / "manim",
        ]

        found_cmd = None
        for candidate in candidates:
            if candidate.exists() and os.access(candidate, os.X_OK):
                if candidate.name.startswith("python"):
                    found_cmd = [str(candidate), "-m", "manim"]
                else:
                    found_cmd = [str(candidate)]
                break

        if not found_cmd:
            sys_manim = shutil.which("manim")
            if sys_manim:
                found_cmd = [sys_manim]
            else:
                sys_py = shutil.which("python3")
                if sys_py:
                    chk = subprocess.run([sys_py, "-c", "import manim"], capture_output=True)
                    if chk.returncode == 0:
                        found_cmd = [sys_py, "-m", "manim"]

        if not found_cmd:
            err_msg = (
                "Manim rendering engine was not found on your system.\n\n"
                "To enable 3Blue1Brown video rendering:\n"
                "1. Install Manim: pip install manim (or pacman -S python-manim)\n"
                "2. Or click '💾 Save Scene (.py)' to export this standalone script and render it on any machine."
            )
            self.progress_log.emit(f"\n{err_msg}\n")
            self.render_finished.emit(False, err_msg, "")
            return

        cmd = found_cmd + [
            "render",
            "-ql",
            "--media_dir", self.output_dir,
            self.script_path,
            "GraphAnimationScene",
        ]

        self.progress_log.emit(f"Executing: {' '.join(cmd)}\n")

        try:
            process = subprocess.Popen(
                cmd,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                cwd=str(Path(self.script_path).parent),
            )

            for line in iter(process.stdout.readline, ''):
                self.progress_log.emit(line)

            process.stdout.close()
            ret = process.wait()

            if ret == 0:
                mp4s = list(Path(self.output_dir).rglob("*.mp4"))
                full_mp4s = [p for p in mp4s if "partial_movie_files" not in str(p)]
                target = full_mp4s[-1] if full_mp4s else (mp4s[-1] if mp4s else None)
                self.video_path = str(target) if target else ""
                self.render_finished.emit(True, "Animation rendered successfully!", self.video_path)
            else:
                self.render_finished.emit(False, f"Manim process exited with code {ret}", "")
        except Exception as e:
            self.render_finished.emit(False, f"Render failed: {e}", "")


